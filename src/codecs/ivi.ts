export function decHuffDesc(br: BitReader, descCoded: number, isBlk: boolean): Int32Array | null {
  if (!descCoded) return isBlk ? BLK_VLC[7] : MB_VLC[7];
  const sel = br.get(3);
  if (sel !== 7) return isBlk ? BLK_VLC[sel] : MB_VLC[sel];
  const rows = br.get(4);
  if (!rows) return null;
  const xbits: number[] = [];
  for (let i = 0; i < rows; i++) xbits.push(br.get(4));
  return huffFromDesc(xbits);
}

