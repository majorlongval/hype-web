export const putPixels8x8: InvTransform = (inp, out, o, pitch) => {
  for (let y = 0; y < 64; y += 8, o += pitch) for (let x = 0; x < 8; x++) out[o + x] = inp[y + x];
};

export const dcSlant2d: DcTransform = (dc, out, o, pitch, blkSize) => {
  const v = (dc + 1) >> 1;
  for (let y = 0; y < blkSize; y++, o += pitch) out.fill(v, o, o + blkSize);
};

export const dcRowSlant: DcTransform = (dc, out, o, pitch, blkSize) => {
  out.fill((dc + 1) >> 1, o, o + blkSize);
  for (let y = 1; y < blkSize; y++) out.fill(0, o + y * pitch, o + y * pitch + blkSize);
};

export const dcColSlant: DcTransform = (dc, out, o, pitch, blkSize) => {
  const v = (dc + 1) >> 1;
  for (let y = 0; y < blkSize; y++, o += pitch) {
    out[o] = v;
    out.fill(0, o + 1, o + blkSize);
  }
};

export const putDcPixel8x8: DcTransform = (dc, out, o, pitch) => {
  out[o] = dc;
  out.fill(0, o + 1, o + 8);
  for (let y = 1; y < 8; y++) out.fill(0, o + y * pitch, o + y * pitch + 8);
};

export function mcPut(buf: Int16Array, o: number, ref: Int16Array, r: number, pitch: number, type: number, size: number): void {
  for (let i = 0; i < size; i++, o += pitch, r += pitch) {
    switch (type) {
      case 0: for (let j = 0; j < size; j++) buf[o + j] = ref[r + j]; break;
      case 1: for (let j = 0; j < size; j++) buf[o + j] = (ref[r + j] + ref[r + j + 1]) >> 1; break;
      case 2: for (let j = 0; j < size; j++) buf[o + j] = (ref[r + j] + ref[r + pitch + j]) >> 1; break;
      case 3: for (let j = 0; j < size; j++) buf[o + j] = (ref[r + j] + ref[r + j + 1] + ref[r + pitch + j] + ref[r + pitch + j + 1]) >> 2; break;
    }
  }
}

export function mcAdd(buf: Int16Array, o: number, ref: Int16Array, r: number, pitch: number, type: number, size: number): void {
  for (let i = 0; i < size; i++, o += pitch, r += pitch) {
    switch (type) {
      case 0: for (let j = 0; j < size; j++) buf[o + j] += ref[r + j]; break;
      case 1: for (let j = 0; j < size; j++) buf[o + j] += (ref[r + j] + ref[r + j + 1]) >> 1; break;
      case 2: for (let j = 0; j < size; j++) buf[o + j] += (ref[r + j] + ref[r + pitch + j]) >> 1; break;
      case 3: for (let j = 0; j < size; j++) buf[o + j] += (ref[r + j] + ref[r + j + 1] + ref[r + pitch + j] + ref[r + pitch + j + 1]) >> 2; break;
    }
  }
}

const clip8 = (v: number) => (v < 0 ? 0 : v > 255 ? 255 : v);

export function outputPlane(src: Int16Array | null, pitch: number, w: number, h: number, dst: Uint8Array, dstPitch: number): void {
  if (!src) return;
  for (let y = 0, s = 0, d = 0; y < h; y++, s += pitch, d += dstPitch) {
    for (let x = 0; x < w; x++) dst[d + x] = clip8(src[s + x] + 128);
  }
}

export function recompose53(b0: Int16Array, b1: Int16Array, b2: Int16Array, b3: Int16Array, bandPitch: number, width: number, height: number, dst: Uint8Array, dstPitch: number): void {
  let pitch = bandPitch, backPitch = 0, p = 0, d = 0;
  let b0_1 = 0, b0_2 = 0, b1_1 = 0, b1_2 = 0, b1_3 = 0, b2_1 = 0, b2_2 = 0, b2_3 = 0, b2_4 = 0, b2_5 = 0, b2_6 = 0;
  let b3_1 = 0, b3_2 = 0, b3_3 = 0, b3_4 = 0, b3_5 = 0, b3_6 = 0, b3_7 = 0, b3_8 = 0, b3_9 = 0;
  let p0 = 0, p1 = 0, p2 = 0, p3 = 0, tmp0 = 0, tmp1 = 0, tmp2 = 0;

  for (let y = 0; y < height; y += 2) {
    if (y + 2 >= height) pitch = 0;
    b0_1 = b0[p];
    b0_2 = b0[p + pitch];

    b1_1 = b1[p + backPitch];
    b1_2 = b1[p];
    b1_3 = b1_1 - b1_2 * 6 + b1[p + pitch];

    b2_2 = b2[p];
    b2_3 = b2_2;
    b2_5 = b2[p + pitch];
    b2_6 = b2_5;

    b3_2 = b3[p + backPitch];
    b3_3 = b3_2;
    b3_5 = b3[p];
    b3_6 = b3_5;
    b3_8 = b3_2 - b3_5 * 6 + b3[p + pitch];
    b3_9 = b3_8;

    for (let x = 0, indx = 0; x < width; x += 2, indx++) {
      if (x + 2 >= width) p--;

      b2_1 = b2_2;
      b2_2 = b2_3;
      b2_4 = b2_5;
      b2_5 = b2_6;
      b3_1 = b3_2;
      b3_2 = b3_3;
      b3_4 = b3_5;
      b3_5 = b3_6;
      b3_7 = b3_8;
      b3_8 = b3_9;

      tmp0 = b0_1;
      tmp2 = b0_2;
      b0_1 = b0[p + indx + 1];
      b0_2 = b0[p + pitch + indx + 1];
      tmp1 = tmp0 + b0_1;
      p0 = tmp0 * 16;
      p1 = tmp1 * 8;
      p2 = (tmp0 + tmp2) * 8;
      p3 = (tmp1 + tmp2 + b0_2) * 4;

      tmp0 = b1_2;
      tmp1 = b1_1;
      b1_2 = b1[p + indx + 1];
      b1_1 = b1[p + backPitch + indx + 1];
      tmp2 = tmp1 - tmp0 * 6 + b1_3;
      b1_3 = b1_1 - b1_2 * 6 + b1[p + pitch + indx + 1];
      p0 += (tmp0 + tmp1) * 8;
      p1 += (tmp0 + tmp1 + b1_1 + b1_2) * 4;
      p2 += tmp2 * 4;
      p3 += (tmp2 + b1_3) * 2;

      b2_3 = b2[p + indx + 1];
      b2_6 = b2[p + pitch + indx + 1];
      tmp0 = b2_1 + b2_2;
      tmp1 = b2_1 - b2_2 * 6 + b2_3;
      p0 += tmp0 * 8;
      p1 += tmp1 * 4;
      p2 += (tmp0 + b2_4 + b2_5) * 4;
      p3 += (tmp1 + b2_4 - b2_5 * 6 + b2_6) * 2;

      b3_6 = b3[p + indx + 1];
      b3_3 = b3[p + backPitch + indx + 1];
      tmp0 = b3_1 + b3_4;
      tmp1 = b3_2 + b3_5;
      tmp2 = b3_3 + b3_6;
      b3_9 = b3_3 - b3_6 * 6 + b3[p + pitch + indx + 1];
      p0 += (tmp0 + tmp1) * 4;
      p1 += (tmp0 - tmp1 * 6 + tmp2) * 2;
      p2 += (b3_7 + b3_8) * 2;
      p3 += b3_7 - b3_8 * 6 + b3_9;

      dst[d + x] = clip8((p0 >> 6) + 128);
      dst[d + x + 1] = clip8((p1 >> 6) + 128);
      dst[d + dstPitch + x] = clip8((p2 >> 6) + 128);
      dst[d + dstPitch + x + 1] = clip8((p3 >> 6) + 128);
    }

    d += dstPitch * 2;
    backPitch = -pitch;
    p += pitch + 1;
  }
}

