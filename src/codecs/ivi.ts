export class BitReader {
  buf = new Uint8Array(64);
  idx = 0;
  size = 0;

  reset(data: Uint8Array): void {
    if (this.buf.length < data.length + 16) this.buf = new Uint8Array(data.length + 1024);
    this.buf.set(data);
    this.buf.fill(0, data.length, data.length + 16);
    this.idx = 0;
    this.size = data.length * 8;
  }

  peek(): number {
    const b = this.buf, p = this.idx >> 3;
    return (b[p] | (b[p + 1] << 8) | (b[p + 2] << 16) | (b[p + 3] << 24)) >>> (this.idx & 7);
  }

  skip(n: number): void {
    this.idx = Math.min(this.idx + n, this.size + 8);
  }

  get(n: number): number {
    const v = this.peek() & ((1 << n) - 1);
    this.skip(n);
    return v;
  }

  get32(): number {
    const lo = this.get(16);
    return ((this.get(16) << 16) | lo) >>> 0;
  }

  align(): void {
    const n = -this.idx & 7;
    if (n) this.skip(n);
  }

  left(): number {
    return this.size - this.idx;
  }
}

export const VLC_BITS = 13;

export function readVlc(br: BitReader, tab: Int32Array): number {
  const e = tab[br.peek() & 8191];
  br.skip(e & 255);
  return e >> 8;
}

export function toSigned(v: number): number {
  return v & 1 ? (v >> 1) + 1 : -(v >> 1);
}

const vlcCache = new Map<string, Int32Array | null>();

export function huffFromDesc(xbits: ArrayLike<number>): Int32Array | null {
  const key = Array.prototype.join.call(xbits, ",");
  const hit = vlcCache.get(key);
  if (hit !== undefined) return hit;
  const tab = new Int32Array(1 << VLC_BITS).fill(-256);
  const rows = xbits.length;
  let pos = 0, ok = true;
  build: for (let i = 0; i < rows; i++) {
    const codesPerRow = 1 << xbits[i];
    const notLast = i !== rows - 1 ? 1 : 0;
    const prefix = ((1 << i) - 1) << (xbits[i] + notLast);
    for (let j = 0; j < codesPerRow; j++) {
      if (pos >= 256) break build;
      let len = i + xbits[i] + notLast;
      if (len > VLC_BITS) {
        ok = false;
        break build;
      }
      const code = prefix | j;
      if (!len) len = 1;
      let rev = 0;
      for (let k = 0; k < len; k++) rev |= ((code >> k) & 1) << (len - 1 - k);
      for (let e = rev; e < tab.length; e += 1 << len) tab[e] = (pos << 8) | len;
      pos++;
    }
  }
  const out = ok ? tab : null;
  vlcCache.set(key, out);
  return out;
}

