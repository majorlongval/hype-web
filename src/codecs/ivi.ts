const T = new Int32Array(8);
const TMP = new Int32Array(64);

function slant8(s1: number, s4: number, s8: number, s5: number, s2: number, s6: number, s3: number, s7: number): void {
  let t0 = s5 + ((s4 * 4 - s5 + 4) >> 3);
  let t5 = s4 + ((-s4 - s5 * 4 + 4) >> 3);
  let t4 = t0;
  t0 = s1 - t5; let t1 = s1 + t5; t5 = t0;
  t0 = s2 - s6; let t2 = s2 + s6; let t6 = t0;
  t0 = s7 - s3; let t7 = s7 + s3; let t3 = t0;
  t0 = t4 - s8; t4 = t4 + s8; let t8 = t0;

  t0 = t1 - t2; t1 = t1 + t2; t2 = t0;
  t0 = ((t4 + t3 * 2 + 2) >> 2) + t4; t3 = ((t4 * 2 - t3 + 2) >> 2) - t3; t4 = t0;
  t0 = t5 - t6; t5 = t5 + t6; t6 = t0;
  t0 = ((t8 + t7 * 2 + 2) >> 2) + t8; t7 = ((t8 * 2 - t7 + 2) >> 2) - t7; t8 = t0;
  t0 = t1 - t4; t1 = t1 + t4; t4 = t0;
  t0 = t2 - t3; t2 = t2 + t3; t3 = t0;
  t0 = t5 - t8; t5 = t5 + t8; t8 = t0;
  t0 = t6 - t7; t6 = t6 + t7; t7 = t0;

  T[0] = t1; T[1] = t2; T[2] = t3; T[3] = t4; T[4] = t5; T[5] = t6; T[6] = t7; T[7] = t8;
}

function slant4(s1: number, s4: number, s2: number, s3: number): void {
  let t0 = s1 - s2; let t1 = s1 + s2; let t2 = t0;
  t0 = ((s4 + s3 * 2 + 2) >> 2) + s4; let t3 = ((s4 * 2 - s3 + 2) >> 2) - s3; let t4 = t0;
  t0 = t1 - t4; t1 = t1 + t4; t4 = t0;
  t0 = t2 - t3; t2 = t2 + t3; t3 = t0;
  T[0] = t1; T[1] = t2; T[2] = t3; T[3] = t4;
}

export const inverseSlant8x8: InvTransform = (inp, out, o, pitch, flags) => {
  for (let i = 0; i < 8; i++) {
    if (flags[i]) {
      slant8(inp[i], inp[8 + i], inp[16 + i], inp[24 + i], inp[32 + i], inp[40 + i], inp[48 + i], inp[56 + i]);
      for (let k = 0; k < 8; k++) TMP[k * 8 + i] = T[k];
    } else {
      for (let k = 0; k < 8; k++) TMP[k * 8 + i] = 0;
    }
  }
  for (let i = 0; i < 64; i += 8, o += pitch) {
    if (!TMP[i] && !TMP[i + 1] && !TMP[i + 2] && !TMP[i + 3] && !TMP[i + 4] && !TMP[i + 5] && !TMP[i + 6] && !TMP[i + 7]) {
      out.fill(0, o, o + 8);
    } else {
      slant8(TMP[i], TMP[i + 1], TMP[i + 2], TMP[i + 3], TMP[i + 4], TMP[i + 5], TMP[i + 6], TMP[i + 7]);
      for (let k = 0; k < 8; k++) out[o + k] = (T[k] + 1) >> 1;
    }
  }
};

export const inverseSlant4x4: InvTransform = (inp, out, o, pitch, flags) => {
  for (let i = 0; i < 4; i++) {
    if (flags[i]) {
      slant4(inp[i], inp[4 + i], inp[8 + i], inp[12 + i]);
      for (let k = 0; k < 4; k++) TMP[k * 4 + i] = T[k];
    } else {
      for (let k = 0; k < 4; k++) TMP[k * 4 + i] = 0;
    }
  }
  for (let i = 0; i < 16; i += 4, o += pitch) {
    if (!TMP[i] && !TMP[i + 1] && !TMP[i + 2] && !TMP[i + 3]) {
      out[o] = out[o + 1] = out[o + 2] = out[o + 3] = 0;
    } else {
      slant4(TMP[i], TMP[i + 1], TMP[i + 2], TMP[i + 3]);
      for (let k = 0; k < 4; k++) out[o + k] = (T[k] + 1) >> 1;
    }
  }
};

